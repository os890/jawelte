package org.os890.jawelte.tests.lnp.scenario08.entity.finance;

import java.util.ArrayList;
import java.util.List;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.OneToMany;

@Entity
public class Budget {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    private String name;

    @jakarta.persistence.Column(name = "budget_year")
    private int year;

    @OneToMany(cascade = CascadeType.ALL, mappedBy = "budget")
    private List<BudgetLine> lines = new ArrayList<>();

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getYear() {
        return year;
    }

    public void setYear(int year) {
        this.year = year;
    }

    public List<BudgetLine> getLines() {
        return lines;
    }

    public void setLines(List<BudgetLine> lines) {
        this.lines = lines;
    }
}
